"""Export the Python card renderer as a browser template, keeping both designs aligned."""

from pathlib import Path
import argparse
import base64
import json
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from ship_a_big_mac.git_release import ReleaseContext
from ship_a_big_mac.planner import FeastPlan
from ship_a_big_mac.render import render_achievement_svg
from ship_a_big_mac.themes import THEMES


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    context = ReleaseContext("{{repository}}", "main", "{{version}}", 1234, 42, (), 5678, 0, 0, "major", 14)
    plan = FeastPlan("{{strategy}}", 13, 2000000, (), 1234567, "MENU_SUM_NOT_MCP_QUOTED")
    svg = render_achievement_svg(context, plan)
    substitutions = {
        "1234</text>": "{{commits}}</text>", "5678</text>": "{{files}}</text>", "42</text>": "{{makers}}</text>",
        "13 人": "{{people}} 人", "¥12345.67": "{{amount}}", "RELEASE UNLOCKED": "{{eyebrow}}",
        "巨无霸胜利宴": "{{themeName}}", "代码已上线，汉堡安排上。": "{{tagline}}", "#c63028": "{{color}}",
        'font-size="81" font-weight="900" letter-spacing="-3">{{version}}': 'font-size="{{versionSize}}" font-weight="900" letter-spacing="-3">{{version}}',
    }
    for before, after in substitutions.items():
        svg = svg.replace(before, after)
    # WebP keeps the browser payload smaller. Both embedded images derive from
    # the same original menu image; no runtime fetch or canvas CORS dependency.
    png = "data:image/png;base64," + base64.b64encode((ROOT / "ship_a_big_mac/data/feast.png").read_bytes()).decode("ascii")
    webp = "data:image/webp;base64," + base64.b64encode((ROOT / "docs/assets/feast.webp").read_bytes()).decode("ascii")
    svg = svg.replace(png, webp)
    content = "// Generated by scripts/sync_card_template.py from Python render.py and themes.py.\nwindow.CARD_TEMPLATE = " + json.dumps(svg, ensure_ascii=False) + ";\nwindow.CELEBRATION_THEMES = " + json.dumps(THEMES, ensure_ascii=False) + ";\n"
    target = ROOT / "docs/card-template.js"
    if args.check:
        if not target.exists() or target.read_text(encoding="utf-8") != content:
            raise SystemExit("Card template out of sync: run python scripts/sync_card_template.py")
    else:
        target.write_bytes(content.encode("utf-8"))
    print("Card template is synchronized.")


if __name__ == "__main__":
    main()
