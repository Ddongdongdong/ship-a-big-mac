"""Publish the single Python demo fixture for the static site; --check is used in CI."""

from pathlib import Path
import argparse
import json

ROOT = Path(__file__).resolve().parents[1]


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    raw = json.loads((ROOT / "ship_a_big_mac/data/demo-menu.synthetic.json").read_text(encoding="utf-8"))
    payload = json.dumps(raw, ensure_ascii=False, indent=2) + "\n"
    outputs = {
        ROOT / "docs/demo-menu.synthetic.json": payload,
        ROOT / "docs/demo-menu.js": "// Generated by scripts/sync_demo_data.py; edit the Python data fixture.\nwindow.DEMO_MENU = " + payload.rstrip() + ";\n",
    }
    for path, content in outputs.items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                raise SystemExit("Demo data is out of sync: run python scripts/sync_demo_data.py")
        else:
            path.write_bytes(content.encode("utf-8"))
    print("Demo fixture is synchronized.")


if __name__ == "__main__":
    main()
